class AdversarialDebateOrchestrator:
    """Orchestrates debates between honest and adversarial agents."""
    
    def __init__(self, num_honest: int = 3, num_adversarial: int = 2):
        self.honest_agents = []
        self.adversarial_agents = []
        self.governance = TheoryGovernanceSystem()
        self.fusion_engine = CognitiveFusionEngine()
        self.false_evidence_detector = FalseEvidenceDetector()
        self.metrics = DebateMetrics()
        
        # Create honest agents
        honest_types = [
            AgentType.ANALYTICAL,
            AgentType.CREATIVE,
            AgentType.CONSERVATIVE,
            AgentType.OPTIMIZER,
            AgentType.INTEGRATOR
        ]
        
        for i in range(num_honest):
            agent_type = honest_types[i % len(honest_types)]
            self.honest_agents.append(
                HonestAgent(f"honest_{agent_type.value}_{i}", agent_type)
            )
        
        # Create adversarial agents with different strategies
        strategy_list = list(ADVERSARIAL_STRATEGIES.values())
        
        for i in range(num_adversarial):
            strategy = strategy_list[i % len(strategy_list)]
            adv_type = AgentType.MANIPULATOR if i % 2 == 0 else AgentType.DISINFORMER
            self.adversarial_agents.append(
                AdversarialAgent(f"adversarial_{i}", adv_type, strategy)
            )
        
        print(f"[SETUP] Created {num_honest} honest agents and {num_adversarial} adversarial agents")
    
    def run_debate_episode(self, problem: str, episode: int) -> Dict:
        """Run a single debate episode with mixed honest/adversarial agents."""
        self.metrics.total_episodes += 1
        
        # Check if this episode includes adversarial agents
        has_adversarial = len(self.adversarial_agents) > 0 and random.random() < 0.6
        
        if has_adversarial:
            self.metrics.adversarial_episodes += 1
            all_agents = self.honest_agents + self.adversarial_agents
        else:
            all_agents = self.honest_agents
        
        # Phase 1: Generate proposals
        proposals = []
        for agent in all_agents:
            proposal = agent.generate_proposal(problem, episode)
            proposals.append(proposal)
            
            # Track adversarial activity
            if proposal.is_adversarial:
                if proposal.adversarial_strategy == 'false_evidence':
                    self.metrics.false_evidence_injected += 1
                elif proposal.adversarial_strategy == 'logical_fallacies':
                    self.metrics.fallacies_attempted += 1
        
        # Phase 2: Run through governance system
        agent_proposals_dict = {p.agent_id: p.theory for p in proposals}
        
        # Register theories with governance
        for proposal in proposals:
            self.governance.register_synthesized_theory(
                theory=proposal.theory,
                contributing_agents=[proposal.agent_id],
                synthesis_session_id=f"episode_{episode}"
            )
        
        # Detect contradictions (adversarial theories often contradict honest ones)
        honest_theories = [p.theory for p in proposals if not p.is_adversarial]
        adversarial_theories = [p.theory for p in proposals if p.is_adversarial]
        
        for adv_theory in adversarial_theories:
            for honest_theory in honest_theories:
                # Simulate contradiction detection
                if random.random() < 0.7:  # 70% chance of detecting contradiction
                    self.governance.detect_and_register_contradiction(
                        theory_a=honest_theory,
                        theory_b=adv_theory,
                        description="Adversarial theory conflicts with evidence-based approach",
                        severity=0.8
                    )
                    self.metrics.contradictions_caught += 1
        
        # Phase 3: Assess integrity
        for proposal in proposals:
            if proposal.is_adversarial:
                report = self.governance.assess_theory_integrity(proposal.theory.theory_id)
                
                # Check for integrity violations
                if report.integrity_score < 0.7:
                    self.metrics.integrity_violations += 1
                
                # Detect false evidence using FalseEvidenceDetector
                if proposal.adversarial_strategy == 'false_evidence':
                    evidence_report = self.false_evidence_detector.analyze_evidence(
                        proposal.theory.evidence_for[0] if proposal.theory.evidence_for else None,
                        domain="energy"
                    ) if proposal.theory.evidence_for else {'is_suspicious': False}
                    
                    if evidence_report.get('is_suspicious', False):
                        self.metrics.false_evidence_detected += 1
                
                # Detect logical fallacies
                if proposal.adversarial_strategy == 'logical_fallacies':
                    if len(proposal.theory.assumptions) > 0:
                        # Check for fallacious assumptions
                        for assumption in proposal.theory.assumptions:
                            if any(keyword in assumption.lower() for keyword in 
                                   ['either', 'everyone knows', 'obviously']):
                                self.metrics.fallacies_detected += 1
        
        # Phase 4: Attempt synthesis via Cognitive Fusion Engine
        debate_arguments = []  # Simplified for this test
        
        synthesized = self.fusion_engine.run_fusion_pipeline(
            session_id=f"episode_{episode}",
            problem=problem,
            agent_proposals=agent_proposals_dict,
            debate_arguments=debate_arguments,
            verbose=False
        )
        
        # Evaluate outcome
        if synthesized:
            quality = synthesized.quality_score
            
            if has_adversarial:
                # Check if adversarial influence corrupted the synthesis
                adversarial_influence = self._check_adversarial_influence(synthesized, proposals)
                
                if adversarial_influence:
                    self.metrics.manipulated_consensus += 1
                    self.metrics.avg_solution_quality_adversarial = (
                        (self.metrics.avg_solution_quality_adversarial * (self.metrics.adversarial_episodes - 1) + quality) /
                        max(1, self.metrics.adversarial_episodes)
                    )
                else:
                    self.metrics.correct_consensus_reached += 1
                    self.metrics.avg_solution_quality_adversarial = (
                        (self.metrics.avg_solution_quality_adversarial * (self.metrics.adversarial_episodes - 1) + quality) /
                        max(1, self.metrics.adversarial_episodes)
                    )
            else:
                self.metrics.correct_consensus_reached += 1
                self.metrics.avg_solution_quality_clean = (
                    (self.metrics.avg_solution_quality_clean * (episode - 1) + quality) /
                    max(1, episode)
                )
        
        return {
            'episode': episode,
            'has_adversarial': has_adversarial,
            'synthesized': synthesized is not None,
            'quality': synthesized.quality_score if synthesized else 0.0,
            'contradictions_detected': self.metrics.contradictions_caught
        }
    
    def _check_adversarial_influence(self, synthesized, proposals: List[AgentProposal]) -> bool:
        """Check if adversarial agents influenced the synthesis."""
        # Check if adversarial theories contributed to merged components
        adversarial_theory_ids = {p.theory.theory_id for p in proposals if p.is_adversarial}
        
        for component in synthesized.merged_components:
            # Check if any source fragments came from adversarial theories
            for frag_id in component.source_fragments:
                # Fragment IDs contain theory IDs, check for match
                if any(adv_id in frag_id for adv_id in adversarial_theory_ids):
                    return True
        
        return False
    
