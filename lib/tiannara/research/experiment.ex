defmodule Tiannara.Research.Experiment do
  @moduledoc """
  Defines a research experiment: the concrete procedure designed to
  test a hypothesis generated by the Research Director.
  """

  defstruct [
    :id,
    :hypothesis_id,
    :procedure,
    :success_criteria,
    :parameters,
    :duration_cycles,
    :status,
    :result,
    :metrics,
    :created_at,
    :started_at,
    :completed_at,
    rollback_plan: "",
    metadata: %{}
  ]

  @type status :: :proposed | :approved | :running | :completed | :failed | :rolled_back
  @type t :: %__MODULE__{
          id: String.t(),
          hypothesis_id: String.t(),
          procedure: String.t(),
          success_criteria: String.t(),
          parameters: map(),
          duration_cycles: non_neg_integer(),
          status: status(),
          result: atom() | nil,
          metrics: map(),
          created_at: DateTime.t(),
          started_at: DateTime.t() | nil,
          completed_at: DateTime.t() | nil,
          rollback_plan: String.t(),
          metadata: map()
        }

  def new(hypothesis_id, procedure, opts \\ []) do
    %__MODULE__{
      id: "exp_#{System.unique_integer([:positive])}",
      hypothesis_id: hypothesis_id,
      procedure: procedure,
      success_criteria: Map.get(opts, :success_criteria, "Measurable improvement in target metric"),
      parameters: Map.get(opts, :parameters, %{}),
      duration_cycles: Map.get(opts, :duration_cycles, 100),
      status: :proposed,
      result: nil,
      metrics: %{},
      created_at: DateTime.utc_now(),
      rollback_plan: Map.get(opts, :rollback_plan, "Restore pre-experiment state")
    }
  end
end
