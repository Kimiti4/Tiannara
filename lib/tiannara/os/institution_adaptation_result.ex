  @doc """
  Validate constitutional compliance of the adaptation.

  Ensures all invariants are satisfied:
  - Simulation before adoption
  - Pilot before deployment
  - Rollback available
  - Evidence threshold met
  - Governance reviewed
  - Complete history preserved

  ## Parameters
  - `result`: InstitutionAdaptationResult.t()

  ## Returns
  {:compliant, violations} where violations is empty list if compliant
  """
  def validate_constitutional_compliance(result) do
    violations = []

    # Check 1: Must have simulation before adoption
    violations = if result.adoption_decision == :adopted and result.simulation_results == nil do
      [%{rule: "simulation_required", message: "Adoption without prior simulation"} | violations]
    else
      violations
    end

    # Check 2: Must have pilot before adoption
    violations = if result.adoption_decision == :adopted and result.pilot_results == nil do
      [%{rule: "pilot_required", message: "Adoption without prior pilot execution"} | violations]
    else
      violations
    end

    # Check 3: Rollback must be available
    violations = if result.adoption_decision == :adopted and not result.rollback_available do
      [%{rule: "rollback_required", message: "Adoption without rollback capability"} | violations]
    else
      violations
    end

    # Check 4: Governance must have reviewed
    violations = if result.adoption_decision in [:adopted, :rejected] and result.governance_review == nil do
      [%{rule: "governance_review_required", message: "Decision made without governance review"} | violations]
    else
      violations
    end

    # Check 5: All required stages must be completed
    required_stages = [:proposal_received, :compatibility_analyzed, :risk_assessed, :simulated, :piloted, :performance_compared, :governance_reviewed]
    completed_stages = Enum.map(result.stage_history, fn s -> s.stage end)
    missing_stages = Enum.filter(required_stages, fn stage -> stage not in completed_stages end)

    violations = if length(missing_stages) > 0 do
      [%{rule: "incomplete_pipeline", message: "Missing required stages: #{inspect(missing_stages)}"} | violations]
    else
      violations
    end

    compliance = %{
      checked_at: DateTime.utc_now(),
      total_violations: length(violations),
      violations: violations,
      is_compliant: length(violations) == 0
    }

    {%{result | constitutional_compliance: compliance}, violations}
  end

  @doc """
  Build traceability graph linking adaptation to evidence and decisions.

  Creates visualizable graph showing:
  - Which method evolution proposed the improvement
  - Simulation and pilot evidence
  - Governance review outcomes
  - Final adoption decision

  ## Parameters
  - `result`: InstitutionAdaptationResult.t()

  ## Returns
  map() with nodes and edges for visualization
  """
  def build_traceability_graph(result) do
    nodes = []
    edges = []

    # Add improvement node
    improvement_node = %{
      id: "improvement_#{result.improvement_id}",
      type: :improvement,
      label: result.improvement_description,
      category: result.improvement_category
    }
    nodes = [improvement_node | nodes]

    # Add method evolution source node if exists
    nodes = if result.source_method_evolution_id do
      node = %{
        id: "method_evolution_#{result.source_method_evolution_id}",
        type: :method_evolution,
        label: "Method Evolution #{result.source_method_evolution_id}"
      }
      [node | nodes]
    else
      nodes
    end

    # Add simulation node if exists
    nodes = if result.simulation_results do
      node = %{
        id: "simulation_#{result.id}",
        type: :simulation,
        label: "Simulation Results",
        predicted_improvement: result.simulation_results[:predicted_improvement]
      }
      [node | nodes]
    else
      nodes
    end

    # Add pilot node if exists
    nodes = if result.pilot_results do
      node = %{
        id: "pilot_#{result.id}",
        type: :pilot,
        label: "Pilot Results",
        actual_improvement: result.pilot_results[:actual_improvement]
      }
      [node | nodes]
    else
      nodes
    end

    # Add decision node
    decision_node = %{
      id: "decision_#{result.id}",
      type: :decision,
      label: "Adoption Decision: #{inspect(result.adoption_decision)}",
      decision: result.adoption_decision
    }
    nodes = [decision_node | nodes]

    # Add edges
    edges = if result.source_method_evolution_id do
      edge = %{
        from: "method_evolution_#{result.source_method_evolution_id}",
        to: "improvement_#{result.improvement_id}",
        type: :proposed_by
      }
      [edge | edges]
    else
      edges
    end

    edges = if result.simulation_results do
      edge = %{
        from: "improvement_#{result.improvement_id}",
        to: "simulation_#{result.id}",
        type: :simulated
      }
      [edge | edges]
    else
      edges
    end

    edges = if result.pilot_results do
      edge = %{
        from: "improvement_#{result.improvement_id}",
        to: "pilot_#{result.id}",
        type: :piloted
      }
      [edge | edges]
    else
      edges
    end

    decision_edge = %{
      from: "improvement_#{result.improvement_id}",
      to: "decision_#{result.id}",
      type: :decided
    }
    edges = [decision_edge | edges]

    %{
      nodes: nodes,
      edges: edges,
      summary: %{
        total_nodes: length(nodes),
        total_edges: length(edges),
        improvement_id: result.improvement_id,
        final_decision: result.adoption_decision,
        has_simulation: result.simulation_results != nil,
        has_pilot: result.pilot_results != nil
      }
    }
  end
end
