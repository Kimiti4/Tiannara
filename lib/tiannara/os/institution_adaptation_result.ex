defmodule TiannaraOS.InstitutionAdaptationResult do
  @moduledoc """
  InstitutionAdaptationResult - Canonical constitutional transaction for institution adaptation.

  Capability 13.3 - Institution Adaptation

  This artifact captures the evaluation and adoption decision for proposed institutional
  improvements. The institution asks "Which improvement should I adopt?" and performs
  constitutional adaptation through simulation, piloting, and validation.

  ## Constitutional Role

  Institution Adaptation evaluates proposed improvements (generated by Capability 13.2)
  and decides which should become part of the institution. It does NOT generate improvements;
  it evaluates them.

  ## Constitutional Pipeline

  ```
  Receive improvement proposals
      ↓
  Compatibility analysis
      ↓
  Risk assessment
      ↓
  Simulation
      ↓
  Pilot execution
      ↓
  Performance comparison
      ↓
  Governance review
      ↓
  Adoption decision
      ↓
  InstitutionAdaptationResult
  ```

  ## Constitutional Invariants

  1. Simulation before adoption (predict outcomes before committing)
  2. Pilot before deployment (test in controlled environment)
  3. Rollback possible (reversibility preserved)
  4. Evidence threshold satisfied (adoption requires proof)
  5. Governance reviews process—not scientific merit
  6. Complete adaptation history preserved
  7. No irreversible mutation

  ## Adaptation Stages

  - :proposal_received - Improvement proposal from Method Evolution
  - :compatibility_analyzed - Constitutional and operational compatibility checked
  - :risk_assessed - Implementation risks evaluated
  - :simulated - Predictive simulation executed
  - :piloted - Controlled pilot deployment executed
  - :performance_compared - Before/after metrics compared
  - :governance_reviewed - Constitutional compliance verified
  - :adopted - Improvement integrated into institution
  - :rejected - Improvement declined with rationale
  - :rolled_back - Previously adopted improvement reverted

  ## Evaluation Criteria

  - constitutional_compatibility - Does it preserve constitutional integrity?
  - expected_utility - What benefits are predicted?
  - adoption_cost - What resources are required?
  - uncertainty - How confident are predictions?
  - maturity - How well-tested is the improvement?
  - reversibility - Can it be safely rolled back?

  ## Usage

      # Create adaptation result for a proposed improvement
      {:ok, result} = InstitutionAdaptationResult.new(:quantum_lab, %{
        improvement_id: :improved_replication_workflow,
        improvement_category: :replication_workflow
      })

      # Track adaptation stages
      result = InstitutionAdaptationResult.advance_stage(result, :compatibility_analyzed)
      result = InstitutionAdaptationResult.advance_stage(result, :simulated)

      # Record simulation results
      result = InstitutionAdaptationResult.record_simulation(result, %{
        predicted_improvement: 0.25,
        confidence: 0.85,
        side_effects: [:increased_validation_time]
      })

      # Make adoption decision
      result = InstitutionAdaptationResult.make_adoption_decision(result, :adopted, %{
        rationale: "Simulation shows 25% efficiency gain with acceptable trade-offs"
      })
  """

  defstruct [
    # Core identification
    :id,
    :institution_id,
    :adaptation_timestamp,

    # Improvement being evaluated
    :improvement_id,
    :improvement_category,
    :improvement_description,
    :source_method_evolution_id,

    # Adaptation pipeline stage
    :current_stage,
    :stage_history,

    # Evaluation results
    :compatibility_analysis,
    :risk_assessment,
    :simulation_results,
    :pilot_results,
    :performance_comparison,

    # Governance
    :governance_review,
    :constitutional_compliance,

    # Adoption decision
    :adoption_decision,
    :adoption_rationale,
    :adoption_timestamp,

    # Rollback capability
    :rollback_available,
    :rollback_executed,
    :rollback_timestamp,

    # Resource tracking
    :estimated_cost,
    :actual_cost,
    :budget_impact,

    # Constitutional compliance
    :traceability_graph,
    :lifecycle_events,
    :semantic_events,

    # Status
    :status,
    :failure_reason
  ]

  @type t :: %__MODULE__{
    id: String.t(),
    institution_id: atom(),
    adaptation_timestamp: DateTime.t(),
    improvement_id: atom() | String.t(),
    improvement_category: atom(),
    improvement_description: String.t(),
    source_method_evolution_id: String.t() | nil,
    current_stage: atom(),
    stage_history: [map()],
    compatibility_analysis: map() | nil,
    risk_assessment: map() | nil,
    simulation_results: map() | nil,
    pilot_results: map() | nil,
    performance_comparison: map() | nil,
    governance_review: map() | nil,
    constitutional_compliance: map() | nil,
    adoption_decision: atom() | nil,
    adoption_rationale: String.t() | nil,
    adoption_timestamp: DateTime.t() | nil,
    rollback_available: boolean(),
    rollback_executed: boolean(),
    rollback_timestamp: DateTime.t() | nil,
    estimated_cost: map() | nil,
    actual_cost: map() | nil,
    budget_impact: map() | nil,
    traceability_graph: map() | nil,
    lifecycle_events: [map()],
    semantic_events: [map()],
    status: atom(),
    failure_reason: String.t() | nil
  }

  @doc """
  Create a new InstitutionAdaptationResult.

  ## Parameters
  - `institution_id`: atom() - institution identifier
  - `opts`: keyword list or map with optional fields

  ## Returns
  InstitutionAdaptationResult.t()
  """
  def new(institution_id, opts \\ []) do
    opts = if is_map(opts), do: Map.to_list(opts), else: opts

    %__MODULE__{
      id: Keyword.get(opts, :id, "adaptation_#{institution_id}_#{System.monotonic_time(:millisecond)}"),
      institution_id: institution_id,
      adaptation_timestamp: DateTime.utc_now(),
      improvement_id: Keyword.get(opts, :improvement_id),
      improvement_category: Keyword.get(opts, :improvement_category),
      improvement_description: Keyword.get(opts, :improvement_description, ""),
      source_method_evolution_id: Keyword.get(opts, :source_method_evolution_id),
      current_stage: :proposal_received,
      stage_history: [%{stage: :proposal_received, timestamp: DateTime.utc_now()}],
      compatibility_analysis: nil,
      risk_assessment: nil,
      simulation_results: nil,
      pilot_results: nil,
      performance_comparison: nil,
      governance_review: nil,
      constitutional_compliance: nil,
      adoption_decision: nil,
      adoption_rationale: nil,
      adoption_timestamp: nil,
      rollback_available: true,
      rollback_executed: false,
      rollback_timestamp: nil,
      estimated_cost: nil,
      actual_cost: nil,
      budget_impact: nil,
      traceability_graph: nil,
      lifecycle_events: [],
      semantic_events: [],
      status: :pending,
      failure_reason: nil
    }
  end

  @doc """
  Advance adaptation to next stage.

  Records stage transition in history for complete audit trail.

  ## Valid Stage Transitions

  :proposal_received → :compatibility_analyzed
  :compatibility_analyzed → :risk_assessed
  :risk_assessed → :simulated
  :simulated → :piloted
  :piloted → :performance_compared
  :performance_compared → :governance_reviewed
  :governance_reviewed → :adopted | :rejected

  ## Parameters
  - `result`: InstitutionAdaptationResult.t()
  - `new_stage`: atom() - target stage

  ## Returns
  InstitutionAdaptationResult.t()
  """
  def advance_stage(result, new_stage) do
    valid_transitions = %{
      proposal_received: [:compatibility_analyzed],
      compatibility_analyzed: [:risk_assessed],
      risk_assessed: [:simulated],
      simulated: [:piloted],
      piloted: [:performance_compared],
      performance_compared: [:governance_reviewed],
      governance_reviewed: [:adopted, :rejected]
    }

    allowed_next_stages = Map.get(valid_transitions, result.current_stage, [])

    if new_stage not in allowed_next_stages do
      raise ArgumentError,
        message: "Invalid stage transition from #{inspect(result.current_stage)} to #{inspect(new_stage)}. Allowed: #{inspect(allowed_next_stages)}"
    end

    stage_record = %{
      stage: new_stage,
      timestamp: DateTime.utc_now(),
      previous_stage: result.current_stage
    }

    stage_history = result.stage_history ++ [stage_record]

    %{result | current_stage: new_stage, stage_history: stage_history}
  end

  @doc """
  Record compatibility analysis results.

  Evaluates whether the improvement is compatible with:
  - Constitutional principles
  - Existing institutional processes
  - Current resource constraints
  - Other active adaptations

  ## Parameters
  - `result`: InstitutionAdaptationResult.t()
  - `analysis`: map() with keys:
    - :constitutional_compatible - boolean()
    - :operational_compatible - boolean()
    - :resource_feasible - boolean()
    - :conflicts_with_existing - [atom()] list of conflicting adaptations
    - :compatibility_score - float() 0.0-1.0

  ## Returns
  InstitutionAdaptationResult.t()
  """
  def record_compatibility_analysis(result, analysis) do
    %{result | compatibility_analysis: analysis}
  end

  @doc """
  Record risk assessment results.

  Evaluates potential downsides and implementation challenges:
  - Implementation complexity
  - Disruption risk to ongoing research
  - Learning curve for researchers
  - Reversibility confidence
  - Constitutional compatibility risk

  ## Parameters
  - `result`: InstitutionAdaptationResult.t()
  - `assessment`: map() with keys:
    - :implementation_complexity - atom() :low, :medium, :high
    - :disruption_risk - atom() :low, :medium, :high
    - :learning_curve - atom() :shallow, :moderate, :steep
    - :reversibility_confidence - float() 0.0-1.0
    - :identified_risks - [map()] list of specific risks
    - :overall_risk_level - atom() :low, :medium, :high, :critical

  ## Returns
  InstitutionAdaptationResult.t()
  """
  def record_risk_assessment(result, assessment) do
    %{result | risk_assessment: assessment}
  end

  @doc """
  Record simulation results.

  Executes predictive simulation to estimate outcomes before real deployment.

  ## Parameters
  - `result`: InstitutionAdaptationResult.t()
  - `results`: map() with keys:
    - :predicted_improvement - float() expected benefit (0.0-1.0)
    - :confidence - float() prediction confidence (0.0-1.0)
    - :side_effects - [atom()] predicted unintended consequences
    - :resource_requirements - map() predicted resource needs
    - :time_to_benefit - integer() months until benefits realized
    - :simulation_duration - integer() simulated months

  ## Returns
  InstitutionAdaptationResult.t()
  """
  def record_simulation(result, results) do
    %{result | simulation_results: results}
  end

  @doc """
  Record pilot execution results.

  Executes controlled pilot deployment in limited scope to gather real evidence.

  ## Parameters
  - `result`: InstitutionAdaptationResult.t()
  - `results`: map() with keys:
    - :pilot_scope - String.t() description of pilot boundaries
    - :duration_days - integer() pilot duration
    - :actual_improvement - float() measured benefit (0.0-1.0)
    - :participant_feedback - [map()] feedback from pilot participants
    - :unexpected_issues - [map()] issues encountered during pilot
    - :success_metrics - map() quantitative success measurements
    - :pilot_successful - boolean() overall pilot outcome

  ## Returns
  InstitutionAdaptationResult.t()
  """
  def record_pilot_results(result, results) do
    %{result | pilot_results: results}
  end

  @doc """
  Record performance comparison between baseline and adapted methods.

  Compares before/after metrics to quantify actual improvement.

  ## Parameters
  - `result`: InstitutionAdaptationResult.t()
  - `comparison`: map() with keys:
    - :baseline_metrics - map() performance before adaptation
    - :adapted_metrics - map() performance after adaptation
    - :improvement_percentage - float() percent improvement
    - :statistical_significance - float() p-value or confidence
    - :trade_offs - [map()] benefits vs costs analysis

  ## Returns
  InstitutionAdaptationResult.t()
  """
  def record_performance_comparison(result, comparison) do
    %{result | performance_comparison: comparison}
  end

  @doc """
  Record governance review results.

  Constitutional governance verifies process compliance (not scientific merit).

  ## Parameters
  - `result`: InstitutionAdaptationResult.t()
  - `review`: map() with keys:
    - :process_followed - boolean() all stages completed correctly
    - :evidence_sufficient - boolean() enough evidence for decision
    - :constitutional_violations - [String.t()] any violations found
    - :reviewer_id - String.t() governance reviewer identifier
    - :review_timestamp - DateTime.t()
    - :approved_for_adoption - boolean() governance recommendation

  ## Returns
  InstitutionAdaptationResult.t()
  """
  def record_governance_review(result, review) do
    %{result | governance_review: review}
  end

  @doc """
  Make final adoption decision.

  Decides whether to adopt, reject, or defer the improvement.

  ## Parameters
  - `result`: InstitutionAdaptationResult.t()
  - `decision`: atom() - :adopted, :rejected, :deferred
  - `rationale`: map() with keys:
    - :reasoning - String.t() explanation of decision
    - :key_factors - [String.t()] primary considerations
    - :expected_outcomes - [String.t()] anticipated results

  ## Returns
  InstitutionAdaptationResult.t()
  """
  def make_adoption_decision(result, decision, rationale) do
    %{
      result
      | adoption_decision: decision,
        adoption_rationale: inspect(rationale),
        adoption_timestamp: DateTime.utc_now(),
        status: case decision do
          :adopted -> :adopted
          :rejected -> :rejected
          :deferred -> :deferred
        end
    }
  end

  @doc """
  Execute rollback of previously adopted improvement.

  Reverts institution to pre-adaptation state.

  ## Parameters
  - `result`: InstitutionAdaptationResult.t()
  - `rollback_reason`: String.t() why rollback is necessary

  ## Returns
  InstitutionAdaptationResult.t()
  """
  def execute_rollback(result, rollback_reason) do
    if not result.rollback_available do
      raise ArgumentError, message: "Rollback not available for this adaptation"
    end

    %{
      result
      | rollback_executed: true,
        rollback_timestamp: DateTime.utc_now(),
        status: :rolled_back,
        adoption_decision: :rolled_back,
        adoption_rationale: "Rolled back: #{rollback_reason}"
    }
  end

  @doc """
  Set cost estimates and track budget impact.

  ## Parameters
  - `result`: InstitutionAdaptationResult.t()
  - `costs`: map() with keys:
