    - :actual - map() actual costs incurred
    - :budget_variance - float() difference between estimated and actual

  ## Returns
  InstitutionAdaptationResult.t()
  """
  def set_costs(result, costs) do
    %{
      result
      | estimated_cost: costs[:estimated],
        actual_cost: costs[:actual],
        budget_impact: costs[:budget_variance]
    }
  end

